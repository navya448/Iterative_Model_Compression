"""Step 6: collect the numbers quoted in reports/01_ten_seed_evaluation.md into
results/report_tables.md, straight from the CSVs written by steps 1-4 (so the report is not hand-transcribed)."""

import json
import os

import pandas as pd

from common_eval import AUDIT, OUT


def md(df, floatfmt=3):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{floatfmt}f}")
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(out)


def main():
    parts = ["# Report tables (generated by 06_report_tables.py)", ""]
    man = json.load(open(os.path.join(AUDIT, "run_manifest.json")))
    parts += ["## Runs", "", md(pd.DataFrame([dict(run=e["label"], group=e["group"], status=e["status"],
                                                      dense_val_acc=e["dense_val_acc"], target=e["target_val_acc"],
                                                      rounds=" ".join(f"{k}:{v}" for k, v in e["rounds"].items()),
                                                      note=e["reason"]) for e in man["runs"]]), 2), ""]
    parts += ["## Data summary (included runs)", "", md(pd.read_csv(os.path.join(OUT, "data_summary.csv")), 3), ""]
    parts += ["## Formula parameters", "", md(pd.read_csv(os.path.join(OUT, "formula_params.csv")), 4), ""]
    for kind in ("strict", "all"):
        s = pd.read_csv(os.path.join(OUT, f"heldout_summary_{kind}.csv"))
        cols = ["method", "mae_mean", "mae_p05", "mae_p95", "mae_retrain_rounds_mean", "signed_mean",
                "too_late_rate_mean", "too_late_gt_res_mean", "within_res_mean", "unrec_flagged_mean",
                "n_unrecoverable_mean", "false_stop_mean", "saving_vs_tmin_check_mean",
                "saving_vs_tmin_check_p05", "saving_vs_tmin_check_p95"]
        parts += [f"## Held-out summary ({kind})", "", md(s[cols], 3), ""]
        f = pd.read_csv(os.path.join(OUT, f"split_formula_fits_{kind}.csv"))
        g = f.groupby("method")[["a0", "a1", "kappa", "train_rmse", "test_rmse"]].agg(["mean", "std", "min", "max"])
        g.columns = ["_".join(c) for c in g.columns]
        parts += [f"### Formula fits across {kind} splits", "", md(g.reset_index(), 4), ""]
        c = s.iloc[0]
        parts += [f"Costs per split (mean): t_min + check {c['tmin_check_epochs_mean']:.0f} epochs, oracle "
                  f"{c['oracle_epochs_mean']:.0f}, binary search actually run {c['search_epochs_mean']:.0f}.", ""]
    parts += ["## Paired per-seed tests (strict)", "", md(pd.read_csv(os.path.join(OUT, "paired_tests_strict.csv")), 3), ""]
    parts += ["## Split win rates (strict)", "", md(pd.read_csv(os.path.join(OUT, "split_win_rates_strict.csv")), 3), ""]
    parts += ["## Per-seed (strict)", "", md(pd.read_csv(os.path.join(OUT, "per_seed_strict.csv")).query(
        "method in ['Formula (margin 0.1 pp)', 'Formula (margin 0)', 'Sparsity line + check', 'Round median + check']"), 3), ""]
    for name, f, d in [("Budget slopes vs rho", "model_checks_slope_vs_rho.csv", 3),
                       ("Extra-coefficient bootstrap", "model_checks_coef_bootstrap.csv", 4),
                       ("Capacity by round", "model_checks_capacity_by_round.csv", 3),
                       ("Model variants (strict)", "model_checks_variants_strict.csv", 3),
                       ("Variant test-RMSE, margin 0", "model_checks_variants_rmse_margin0.0.csv", 4),
                       ("Per-seed parameters", "model_checks_per_seed_params.csv", 3),
                       ("t* spread by round", "model_checks_tstar_spread_by_round.csv", 2),
                       ("Trade-off sweep", "model_checks_tradeoff_sweep.csv", 3)]:
        df = pd.read_csv(os.path.join(OUT, f))
        if name == "Model variants (strict)":
            df = df[["method", "train_rmse", "test_rmse", "mae_mean", "signed_mean", "too_late_rate_mean",
                     "unrec_flagged_mean", "false_stop_mean", "saving_vs_tmin_check_mean"]]
        parts += [f"## {name}", "", md(df, d), ""]
    for kind in ("pooled", "heldout"):
        p = os.path.join(OUT, f"original_method_{kind}", "rule_scores.csv")
        parts += [f"## Original analyze.py rule scores ({kind}, all rounds of --runs)", "", md(pd.read_csv(p), 2), ""]
        p = os.path.join(OUT, f"original_method_{kind}", "rule_scores_test.csv")
        if os.path.exists(p):
            parts += [f"## Original analyze.py rule scores on --test_runs (8 new runs)", "", md(pd.read_csv(p), 2), ""]
        p = os.path.join(OUT, f"original_method_{kind}", "feature_corr.csv")
        parts += [f"## Original analyze.py feature correlations ({kind})", "", md(pd.read_csv(p), 3), ""]
    open(os.path.join(OUT, "report_tables.md"), "w", encoding="utf-8").write("\n".join(parts))
    print("wrote", os.path.join(OUT, "report_tables.md"))


if __name__ == "__main__":
    main()
